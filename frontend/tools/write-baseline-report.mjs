/**
 * Renders the Gate 4A3 baseline review artifact from the sweep's own JSON output.
 *
 * GENERATED, never hand-written: a report typed by hand can say something the run did not find,
 * and this one is evidence. `npm run audit:baseline` runs the sweep and then this, so the markdown
 * is a view of `gate-4a3-baseline.json` + `gate-4a3-stress.json` and nothing else.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const REVIEW_DIR = path.join(process.cwd(), "..", "docs", "reviews");
const base = JSON.parse(readFileSync(path.join(REVIEW_DIR, "gate-4a3-baseline.json"), "utf-8"));
const stress = JSON.parse(readFileSync(path.join(REVIEW_DIR, "gate-4a3-stress.json"), "utf-8"));

const findings = base.findings ?? [];
const coverage = base.coverage ?? [];
const stressFindings = stress.stressFindings ?? [];
const stressCoverage = stress.stressCoverage ?? [];
const applicability = stress.applicability ?? [];
const authoredNameCount = stress.authoredNameCount ?? 0;

const WCAG = "reflow-wcag-320x512";
const conformance = findings.filter((f) => f.viewport === WCAG);
const belowFloor = findings.filter((f) => f.viewport === "reflow200-mobile-195x422");
const other = findings.filter((f) => f.viewport !== WCAG && f.viewport !== "reflow200-mobile-195x422");

const rows = (list) =>
  list.length === 0
    ? "_None._\n"
    : "| id | screen | viewport | kind | source | detail |\n|---|---|---|---|---|---|\n" +
      list
        .map((f) => `| ${f.id} | ${f.screen} | ${f.viewport} | ${f.kind} | ${f.source} | ${f.detail} |`)
        .join("\n") +
      "\n";

const doc = `# Gate 4A3 baseline — the real-browser review

**Generated by \`npm run audit:baseline\`. Do not hand-edit.** This file is a rendering of
\`gate-4a3-baseline.json\` and \`gate-4a3-stress.json\`, which the sweep writes as it runs.

**This is Commit 1 of six, and it RECORDS ONLY.** Nothing here is fixed. Per the frozen plan §9.1
the sweep exits 0 whenever it completes, whatever it found: a non-zero exit would mean the harness
broke, never that the application has a defect. Triage and fixes are Commit 3, and each fix there
cites a finding id from this file.

## How this was measured

- **The real application.** A production \`mandate-gui\` process serving the built SPA and the real
  scenarios; the campaign is started by clicking the Title screen's own control and is not
  considered started until the server answers \`/api/game/state\` with 200. No mocked \`fetch\`
  anywhere — an earlier draft of this sweep failed to start a campaign and swept eleven empty
  screens, which is why the start is now asserted rather than assumed.
- **The browser already on disk.** Chromium **141.0.7390.37**, revision **1194**, resolved by
  \`@playwright/test\` 1.56.0 through \`PLAYWRIGHT_BROWSERS_PATH\` (a cache root, not an executable
  path). \`e2e/preflight.spec.ts\` proves the pin matches the cache, that the resolved executable
  lives under the cache root, and that the cache listing is byte-identical before and after a
  launch — so nothing was downloaded.
- **Reflow versus device scale, kept apart.** Reflow is emulated the WCAG way by narrowing the CSS
  viewport; the 2× pass is a separate rendering measurement at \`deviceScaleFactor: 2\`. Neither is
  described as "browser zoom" without its qualifier.
- **Live versus stress.** Every finding is tagged. \`live\` means shipped content through the real
  server. \`stress-fixture\` means display names stretched to exactly 64 characters —
  \`StrictDisplayName\`'s documented maximum — served by a SECOND real server from an assembled
  scenario root, so only the content is synthetic.

## The conformance result

**${conformance.length} finding(s) at 320 CSS px**, the width WCAG 2.2 SC 1.4.10 actually requires,
and **no horizontal page scroll at that width on any screen**.

${rows(conformance)}

## Below the conformance floor — recorded, not counted against conformance

Halving the 390 px phone viewport for 200% zoom yields **195 CSS px, which is narrower than the
320 px floor the standard requires**. These are real observations of a real user situation and are
listed in full, but they are **not** conformance failures, and Commit 3 should triage them as such.

The first run of this sweep reported 35 findings and every one of them was here, with nothing at
any other viewport — which is exactly why the 320 px case was added before this baseline was
recorded rather than after.

${rows(belowFloor)}

## Everything else

Findings at the three real viewports (1920×1080, 1440×900, 820×900) and the desktop/laptop reflow
cases:

${rows(other)}

## Stress pass — maximum-length names, per screen

**Commit 1's broad "0 stress findings" claim was UNSUPPORTED, and this section replaces it.** That
commit reported a clean stress result for four screens on the strength of a single assertion — that
some text node of at least 60 characters had rendered. A read-only probe showed the node it matched
was Dashboard *prose*, not a stressed name. Measured per screen, the authored 64-character names
reached Relationships and reached none of Dashboard, Government or Decisions, so three quarters of
that clean result was an absent check wearing the look of a clean one.

A screen is now either **stress-applicable**, in which case the exact authored name must be proven
present before any result is recorded for it, or **not-stress-applicable**, in which case the reason
is stated and no result is claimed. ${authoredNameCount} authored names in the fixture, each exactly
64 characters.

| screen | stress-applicable | why |
|---|---|---|
${applicability.map((a) => `| ${a.screen} | ${a.applicable ? "**yes**" : "no"} | ${a.reason} |`).join("\n")}

What was proven, and what was declined:

${stressCoverage.map((c) => `- ${c}`).join("\n")}

Findings on the stress-applicable screen(s) only:

${rows(stressFindings)}

## Checked and found CLEAN

An absent finding is otherwise indistinguishable from an absent check, so what was looked at and
found sound is recorded explicitly:

${coverage.map((c) => `- ${c}`).join("\n")}

## Coverage

- Screens swept: Dashboard, Government, Economy, Legislature, Constitution, Relationships,
  Decisions, Turn result, History, Strategic map, Victory / defeat, plus the chrome-level Glossary.
- Viewport cases: ${base.viewports.map((v) => v.name).join(", ")}, plus a 2× device-scale pass.
- Screenshots: \`docs/reviews/gate-4a3-baseline/\`.
- Totals: **${findings.length} live finding(s)**, **${stressFindings.length} stress finding(s)**,
  **${coverage.length} clean-result record(s)**.
`;

writeFileSync(path.join(REVIEW_DIR, "gate-4a3-baseline.md"), doc, "utf-8");
console.log(
  `baseline report written: ${findings.length} live, ${stressFindings.length} stress, ${coverage.length} clean`,
);
